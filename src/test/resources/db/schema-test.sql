CREATE TABLE IF NOT EXISTS "technologies" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR_IGNORECASE(50) NOT NULL UNIQUE,
    description VARCHAR(90) NOT NULL
);

CREATE TABLE IF NOT EXISTS "capacity_technologies" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacity_id BIGINT NOT NULL,
    technology_id BIGINT NOT NULL REFERENCES "technologies"(id),
    UNIQUE (capacity_id, technology_id)
);
